export type Unsubscribe = () => void;

type EventKey<TEvents extends object> = Extract<keyof TEvents, string>;
type UnknownListener = (payload: unknown) => void;

/**
 * ??????????????????????
 * ?????????????????? on/emit ????????
 */
export class EventBus<TEvents extends object> {
  private readonly listeners = new Map<EventKey<TEvents>, Set<UnknownListener>>();

  /**
   * ?????
   * @param event ???????????
   * @param listener ???????????
   * @returns ????????????
   */
  public on<TKey extends EventKey<TEvents>>(
    event: TKey,
    listener: (payload: TEvents[TKey]) => void,
  ): Unsubscribe {
    const wrapped: UnknownListener = (payload) => listener(payload as TEvents[TKey]);
    const eventListeners = this.listeners.get(event) ?? new Set<UnknownListener>();
    eventListeners.add(wrapped);
    this.listeners.set(event, eventListeners);

    let subscribed = true;
    return () => {
      if (!subscribed) return;
      subscribed = false;
      eventListeners.delete(wrapped);
      if (eventListeners.size === 0) this.listeners.delete(event);
    };
  }

  /**
   * ????????????????????
   * @param event ???????????
   * @param listener ??????????
   * @returns ???????????????
   */
  public once<TKey extends EventKey<TEvents>>(
    event: TKey,
    listener: (payload: TEvents[TKey]) => void,
  ): Unsubscribe {
    let unsubscribe: Unsubscribe = () => undefined;
    unsubscribe = this.on(event, (payload) => {
      unsubscribe();
      listener(payload);
    });
    return unsubscribe;
  }

  /**
   * ???????
   * @param event ???????????
   * @param payload ??????????
   */
  public emit<TKey extends EventKey<TEvents>>(event: TKey, payload: TEvents[TKey]): void {
    const eventListeners = this.listeners.get(event);
    if (!eventListeners) return;

    // ??????????????????????????????
    for (const listener of Array.from(eventListeners)) listener(payload);
  }

  /**
   * ????????????????
   * @param event ??????????????????
   */
  public clear(event?: EventKey<TEvents>): void {
    if (event === undefined) this.listeners.clear();
    else this.listeners.delete(event);
  }

  /** ????????????????????????? */
  public listenerCount(event: EventKey<TEvents>): number {
    return this.listeners.get(event)?.size ?? 0;
  }
}
