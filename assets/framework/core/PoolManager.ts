export class PoolManager {
  private readonly pools = new Set<ManagedPool>();

  /**
   * ?????????????
   * @param factory ???????
   * @param options ????????????
   * @returns ?????????????
   */
  public createPool<T extends Poolable>(
    factory: PoolFactory<T>,
    options: PoolOptions = {},
  ): ObjectPool<T> {
    const pool = new ObjectPool(factory, options);
    this.pools.add(pool);
    return pool;
  }

  /**
   * ???????????
   * @param pool ???????????
   * @returns ???????? true?
   */
  public destroyPool<T extends Poolable>(pool: ObjectPool<T>): boolean {
    if (!this.pools.delete(pool)) return false;
    pool.destroy();
    return true;
  }

  /** ?????????????? */
  public clear(): void {
    for (const pool of this.pools) pool.destroy();
    this.pools.clear();
  }
}
