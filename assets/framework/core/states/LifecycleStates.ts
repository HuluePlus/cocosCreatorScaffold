import type { State } from '../StateMachine';

/** ??????????? */
export type LifecycleStateId = 'idle' | 'running' | 'paused' | 'destroyed';

/**
 * ?????????GameManager ?????????????????
 */
export interface GameLifecycleHooks {
  readonly onStart: () => void;
  readonly onPause: () => void;
  readonly onResume: () => void;
  readonly onDestroy: () => void;
}

/** ????????????????????????? */
export abstract class LifecycleState implements State<GameLifecycleHooks, LifecycleStateId> {
  public abstract readonly id: LifecycleStateId;

  /** ????????????????????? */
  public abstract enter(context: GameLifecycleHooks, previous: LifecycleStateId | null): void;

  /** ???????????????????????????????? */
  public exit(_context: GameLifecycleHooks, _next: LifecycleStateId): void {}
}

/** ????????? GameManager.start ????? */
export class IdleState extends LifecycleState {
  public readonly id = 'idle' as const;

  /** ???????????? */
  public enter(_context: GameLifecycleHooks, _previous: LifecycleStateId | null): void {}
}

/** ????????????????????????? */
export class RunningState extends LifecycleState {
  public readonly id = 'running' as const;

  /** ?????????????????? */
  public enter(context: GameLifecycleHooks, previous: LifecycleStateId | null): void {
    if (previous === 'paused') context.onResume();
    else context.onStart();
  }
}

/** ????????????????????????? */
export class PausedState extends LifecycleState {
  public readonly id = 'paused' as const;

  /** ????????????? */
  public enter(context: GameLifecycleHooks, _previous: LifecycleStateId | null): void {
    context.onPause();
  }
}

/** ??????????????????????? */
export class DestroyedState extends LifecycleState {
  public readonly id = 'destroyed' as const;

  /** ?????????????? */
  public enter(context: GameLifecycleHooks, _previous: LifecycleStateId | null): void {
    context.onDestroy();
  }
}
