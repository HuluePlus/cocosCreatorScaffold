export abstract class BaseEntity<TContext> extends Component implements Poolable {
  private initialized = false;
  private contextValue: TContext | null = null;

  /** ??????????????????????? */
  protected get context(): TContext {
    if (!this.initialized) throw new Error('Entity has not been initialized');
    return this.contextValue as TContext;
  }

  /**
   * ??????????????????????????/???????????
   * @param context ?????????????
   */
  public initialize(context: TContext): void {
    if (this.initialized) throw new Error('Entity has already been initialized');
    this.contextValue = context;
    this.initialized = true;
    this.onInitialize(context);
  }

  /** ??????????????????????? */
  public onAcquireFromPool(): void {
    if (!this.initialized) throw new Error('Entity must be initialized before activation');
    this.node.active = true;
    this.onEntityActivated();
  }

  /** ?????????????????????? */
  public onReleaseToPool(): void {
    this.onEntityDeactivated();
    this.node.active = false;
  }

  /** ?????????????? Cocos ??? */
  public onDestroyFromPool(): void {
    if (this.node.isValid) this.node.destroy();
  }

  /**
   * ????????????
   * @param context ??????????
   */
  protected abstract onInitialize(context: TContext): void;

  /** ??????????????????? */
  protected onEntityActivated(): void {}

  /** ????????????????? */
  protected onEntityDeactivated(): void {}
}
